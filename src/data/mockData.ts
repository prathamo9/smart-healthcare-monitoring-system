// Helper to generate dates relative to today
const createDate = (daysAgo: number, timeStr: string) => {
  const d = new Date();
  d.setDate(d.getDate() - daysAgo);
  const isoDate = d.toISOString().split('T')[0];
  return `${isoDate} ${timeStr}`;
};

